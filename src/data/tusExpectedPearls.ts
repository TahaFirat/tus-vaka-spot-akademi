// Deterministic 2-hour rotation slot shared identically between Swift WidgetKit & TypeScript
export function getExpectedPearlIndexForTime(nowMs = Date.now()): number {
  const twoHourSlot = Math.floor(nowMs / (2 * 3600 * 1000));
  return Math.abs(twoHourSlot) % TUS_EXPECTED_PEARLS.length;
}

export function getActiveExpectedPearl(
  pinnedPearlId?: string | null,
  nowMs = Date.now()
): TusExpectedPearl {
  if (pinnedPearlId) {
    const found = TUS_EXPECTED_PEARLS.find((p) => p.id === pinnedPearlId);
    if (found) return found;
  }
  return TUS_EXPECTED_PEARLS[getExpectedPearlIndexForTime(nowMs)];
}
